    // Index du projet actuellement affiché
    public $currentIndex = 0;

    // Liste des projets (normalement chargés depuis la base de données)
    public $projects = [];

    public function mount(): void
    {
        // En production, vous pourriez charger les projets depuis la base de données
        // Ici, nous utilisons des données d'exemple
        $this->projects = $this->getExampleProjects();
    }

    // Passer au projet suivant
    public function nextProject(): void
    {
        $this->currentIndex = ($this->currentIndex === count($this->projects) - 1)
            ? 0
            : $this->currentIndex + 1;
    }

    // Passer au projet précédent
    public function prevProject()
    {
        $this->currentIndex = ($this->currentIndex === 0)
            ? count($this->projects) - 1
            : $this->currentIndex - 1;
    }

    // Aller à un projet spécifique
    public function goToProject($index)
    {
        if ($index >= 0 && $index < count($this->projects)) {
            $this->currentIndex = $index;
        }
    }

    public function render()
    {
        return view('livewire.project-carousel', [
            'currentProject' => $this->projects[$this->currentIndex]
        ]);
    }

